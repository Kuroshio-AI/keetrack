// A fresh, unanswered checklist from a template. Ids run across sections so they stay unique.
export function checklistFrom(template: ChecklistTemplate): ChecklistItem[] {
  return template.sections.flatMap(([section, items]) => items.map((label) => ({ section, label }))).map((item, index) => ({ id: `check-${index + 1}`, ...item, result: "pending" as const }));
}
